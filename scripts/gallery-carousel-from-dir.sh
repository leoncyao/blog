#!/usr/bin/env bash
# Usage (run from blog root):
#   ./scripts/gallery-carousel-from-dir.sh                    # list assets/Images/2026
#   ./scripts/gallery-carousel-from-dir.sh assets/Images/2026
#   ./scripts/gallery-carousel-from-dir.sh assets/Images/2026 _posts/2025-02-14-EuropeTrip.md  # append carousel to post
# Outputs HTML for a gallery carousel (paste into any post). Optional: pass a .md file to insert after first paragraph.

set -e
# Usage: run from blog root with no args, or: script [gallery_dir] [post.md]
GALLERY_DIR="${1:-assets/Images/2026}"
POST_FILE="${2:-}"
DIR="$GALLERY_DIR"
BASE_PATH="/${GALLERY_DIR}"
OUTPUT_TMP=
trap '[[ -n "$OUTPUT_TMP" && -f "$OUTPUT_TMP" ]] && rm -f "$OUTPUT_TMP"' EXIT

# Image and video extensions
IMG_EXTS="jpg jpeg png gif webp bmp svg"
VID_EXTS="mp4 webm mov m4v ogv"

all_files=()
for ext in $IMG_EXTS $VID_EXTS; do
  if [[ -d "$DIR" ]]; then
    while IFS= read -r -d '' f; do
      all_files+=("$(basename "$f")")
    done < <(find "$DIR" -maxdepth 1 -iname "*.${ext}" -print0 2>/dev/null || true)
  fi
done

# Sort and dedupe
sorted=($(printf '%s\n' "${all_files[@]}" | sort -V))

if [[ ${#sorted[@]} -eq 0 ]]; then
  echo "No images or videos found in $DIR" >&2
  echo "Create the folder and add files, or run: $0 [gallery_dir] [post.md]" >&2
  exit 1
fi

OUTPUT_TMP=$(mktemp)

# Escape for HTML attribute
escape_attr() { echo "$1" | sed 's/&/\&amp;/g; s/</\&lt;/g; s/>/\&gt;/g; s/"/\&quot;/g'; }

lower() { echo "$1" | tr '[:upper:]' '[:lower:]'; }

is_video() {
  local ext=$(lower "${1##*.}")
  case "$ext" in
    mp4|webm|mov|m4v|ogv) return 0 ;;
    *) return 1 ;;
  esac
}

{
echo '<!-- Gallery carousel generated by scripts/gallery-carousel-from-dir.sh -->'
echo '<div class="gallery-carousel" data-auto-rotate="4">'
echo '  <button type="button" class="carousel-btn carousel-prev" aria-label="Previous">‹</button>'
echo '  <div class="carousel-inner">'

i=0
for file in "${sorted[@]}"; do
  ext="${file##*.}"
  escaped=$(escape_attr "$file")
  class="carousel-slide"
  [[ $i -eq 0 ]] && class="$class active"
  echo "    <div class=\"$class\" data-index=\"$i\">"
  if is_video "$file"; then
    echo "      <video controls loop muted playsinline preload=\"metadata\"><source src=\"{{site.baseurl}}${BASE_PATH}/$escaped\" type=\"video/$(lower $ext)\"></video>"
  else
    echo "      <img src=\"{{site.baseurl}}${BASE_PATH}/$escaped\" alt=\"\" loading=\"lazy\">"
  fi
  echo "    </div>"
  (( i++ )) || true
done

echo '  </div>'
echo '  <button type="button" class="carousel-btn carousel-next" aria-label="Next">›</button>'
echo '  <div class="carousel-dots"></div>'
echo '</div>'

echo '<style>'
cat << 'CAROUSEL_CSS'
.gallery-carousel { position: relative; max-width: 100%; margin: 1rem 0; }
.gallery-carousel .carousel-inner {
  position: relative; width: 100%; overflow: hidden;
  border-radius: 8px; background: #111;
}
.gallery-carousel .carousel-slide {
  display: none; width: 100%; text-align: center;
}
.gallery-carousel .carousel-slide.active { display: block; }
.gallery-carousel .carousel-slide img,
.gallery-carousel .carousel-slide video {
  max-width: 100%; max-height: 70vh; width: auto; height: auto;
  vertical-align: middle;
}
.gallery-carousel .carousel-btn {
  position: absolute; top: 50%; transform: translateY(-50%);
  z-index: 2; width: 44px; height: 44px; padding: 0;
  border: none; border-radius: 50%; background: rgba(0,0,0,0.5);
  color: #fff; font-size: 1.5rem; cursor: pointer;
  transition: background .2s;
}
.gallery-carousel .carousel-btn:hover { background: rgba(0,0,0,0.8); }
.gallery-carousel .carousel-prev { left: 8px; }
.gallery-carousel .carousel-next { right: 8px; }
.gallery-carousel .carousel-dots {
  text-align: center; margin-top: 8px; min-height: 1.5rem;
}
.gallery-carousel .carousel-dot {
  display: inline-block; width: 10px; height: 10px; margin: 0 4px;
  border-radius: 50%; background: #ccc; border: none; cursor: pointer;
  padding: 0;
}
.gallery-carousel .carousel-dot.active { background: #333; }
CAROUSEL_CSS
echo '</style>'

echo '<script>'
cat << 'CAROUSEL_JS'
(function(){
  var wrap = document.querySelector('.gallery-carousel');
  if (!wrap) return;
  var inner = wrap.querySelector('.carousel-inner');
  var slides = inner.querySelectorAll('.carousel-slide');
  var prev = wrap.querySelector('.carousel-prev');
  var next = wrap.querySelector('.carousel-next');
  var dotsEl = wrap.querySelector('.carousel-dots');
  var n = slides.length;
  var idx = 0;
  var autoMs = parseInt(wrap.dataset.autoRotate || '0', 10) * 1000;
  var timer = null;

  function go(i) {
    idx = (i + n) % n;
    slides.forEach(function(s, k){ s.classList.toggle('active', k === idx); });
    var dots = dotsEl.querySelectorAll('.carousel-dot');
    dots.forEach(function(d, k){ d.classList.toggle('active', k === idx); });
  }

  for (var i = 0; i < n; i++) {
    var d = document.createElement('button');
    d.type = 'button';
    d.className = 'carousel-dot' + (i === 0 ? ' active' : '');
    d.setAttribute('aria-label', 'Slide ' + (i + 1));
    (function(j){ d.addEventListener('click', function(){ go(j); resetTimer(); }); })(i);
    dotsEl.appendChild(d);
  }

  if (prev) prev.addEventListener('click', function(){ go(idx - 1); resetTimer(); });
  if (next) next.addEventListener('click', function(){ go(idx + 1); resetTimer(); });

  function resetTimer() {
    if (timer) clearInterval(timer);
    if (autoMs > 0) timer = setInterval(function(){ go(idx + 1); }, autoMs);
  }
  if (autoMs > 0) resetTimer();
})();
CAROUSEL_JS
echo '</script>'
} > "$OUTPUT_TMP"

if [[ -n "$POST_FILE" && -f "$POST_FILE" ]]; then
  echo "" >> "$POST_FILE"
  cat "$OUTPUT_TMP" >> "$POST_FILE"
  echo "Carousel appended to $POST_FILE ($(wc -l < "$OUTPUT_TMP") lines)." >&2
else
  cat "$OUTPUT_TMP"
fi
